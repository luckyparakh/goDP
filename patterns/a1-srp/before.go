package srp

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// PROBLEM
//
// Process does three different jobs in one function:
//
//  1. adds up the bill (tax rules live here)
//  2. writes the receipt text (wording lives here)
//  3. saves the text to a file (storage lives here)
//
// A tax change, a wording change and a storage change all edit this one
// function. And to check one sum you have to run all three jobs.
//
// TRY IT
//
// Look at the signature: Process(dir). You cannot ask for the sum without
// also giving it a folder to save into. Read
// TestBefore_BrokenFolderTurnsASumIntoAnError in srp_test.go: with a missing
// folder you get an error instead of a sum. (Process could have returned the
// sum together with the error. Even then, the sum can only be reached by
// going through the save.)
//
// Do not edit this file. Your work goes in after.go.

// Item is one bill line. Amounts are in cents so the arithmetic is exact.
type Item struct {
	Name      string
	UnitCents int64
	Qty       int64
}

// Invoice is shared by the "before" and "after" code.
type Invoice struct {
	Items      []Item
	TaxPercent int64
}

func money(cents int64) string {
	return fmt.Sprintf("%d.%02d", cents/100, cents%100)
}

// Process totals the invoice, builds a receipt and writes it to dir/receipt.txt.
func (inv Invoice) Process(dir string) (int64, error) {
	var subtotal int64
	for _, it := range inv.Items {
		subtotal += it.UnitCents * it.Qty
	}
	total := subtotal + subtotal*inv.TaxPercent/100

	var b strings.Builder
	for _, it := range inv.Items {
		fmt.Fprintf(&b, "%s x%d %s\n", it.Name, it.Qty, money(it.UnitCents*it.Qty))
	}
	fmt.Fprintf(&b, "TOTAL %s\n", money(total))

	if err := os.WriteFile(filepath.Join(dir, "receipt.txt"), []byte(b.String()), 0o644); err != nil {
		return 0, fmt.Errorf("write receipt: %w", err)
	}
	return total, nil
}
