// Metrics counts named events.
type Metrics interface {
	Inc(name string)
}

// ErrBadAmount is returned for an amount of zero or less.
var ErrBadAmount = errors.New("amount must be positive")

// ServiceBefore takes payments. Its logger and metrics may both be nil.
type ServiceBefore struct {
	log     *slog.Logger
	metrics Metrics
}

// NewServiceBefore returns a ServiceBefore. log and m may be nil.
func NewServiceBefore(log *slog.Logger, m Metrics) *ServiceBefore {
	return &ServiceBefore{log: log, metrics: m}
}

// Charge takes a payment, in cents.
func (s *ServiceBefore) Charge(cents int64) error {
	if cents <= 0 {
		if s.metrics != nil {
			s.metrics.Inc("charge_rejected")
		}
		return ErrBadAmount
	}
	if s.log != nil {
		s.log.Info("charge", "cents", cents)
	}
	if s.metrics != nil {
		s.metrics.Inc("charges")
	}
	return nil
}

// Refund gives a payment back, in cents.
func (s *ServiceBefore) Refund(cents int64) error {
	if cents <= 0 {
		return ErrBadAmount
	}
	if s.log != nil {
		s.log.Info("refund", "cents", cents)
	}
	s.metrics.Inc("refunds") // the nil check was forgotten here
	return nil
}
