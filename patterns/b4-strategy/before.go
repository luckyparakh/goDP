// PROBLEM
//
// RetryBefore picks its wait between attempts by name, through a switch in
// Delay. Every new policy means editing that switch. Worse, the name is a
// plain string: a typo compiles fine, falls into the default case, and quietly
// waits the wrong time. Nobody finds out until production retries too fast.
//
// TRY IT
//
// Read TestBefore_TypoFallsBackSilently in strategy_test.go. "exponental"
// compiles, returns no error and gives the constant delay.
//
// Then imagine adding a "jitter" policy. You would edit Delay, and every
// caller would have to type the new name exactly right.
//
// Do not edit this file. Your work goes in after.go.

// ErrNoAttempts is returned when Retry is asked for fewer than one attempt.
var ErrNoAttempts = errors.New("retry: attempts must be at least 1")

// Delay says how long to wait before retry number attempt, where 1 is the
// first retry.
func Delay(policy string, attempt int) time.Duration {
	const base = 100 * time.Millisecond
	switch policy {
	case "constant":
		return base
	case "linear":
		return base * time.Duration(attempt)
	case "exponential":
		d := base
		for i := 1; i < attempt && d < time.Second; i++ {
			d *= 2
		}
		return min(d, time.Second)
	default:
		return base // an unknown name quietly gets the constant delay
	}
}

// RetryBefore runs op up to attempts times. Between attempts it sleeps for
// Delay(policy, n). It returns nil on the first success, or the last error.
func RetryBefore(attempts int, policy string, sleep func(time.Duration), op func() error) error {
	if attempts < 1 {
		return ErrNoAttempts
	}
	var err error
	for n := 1; n <= attempts; n++ {
		if err = op(); err == nil {
			return nil
		}
		if n < attempts {
			sleep(Delay(policy, n))
		}
	}
	return fmt.Errorf("after %d attempts: %w", attempts, err)
}
