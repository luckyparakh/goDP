package embedding

// PROBLEM
//
// Derived embeds Base and replaces its Name method. If you know Java or C++
// you expect Base's Hello to start using the new name, because "Derived is a
// Base". In Go it does not. Hello was written on Base, so inside it the
// receiver is a Base, and Base's own Name is called. Embedding forwards
// methods. It does not make Derived a subtype of Base, and it does not let a
// method on Base see what Derived changed.
//
// TRY IT
//
// Before you open embedding_test.go, guess what Derived{}.Hello() returns.
// Then read TestBefore_HelloIgnoresTheOverride and see if you were right.
//
// Do not edit this file. Your work goes in after.go.

// Namer is anything that has a name.
type Namer interface {
	Name() string
}

// Base has a name and builds a greeting from it.
type Base struct{}

func (Base) Name() string { return "base" }

// Hello greets using the receiver's Name.
func (b Base) Hello() string { return "hello from " + b.Name() }

// Derived embeds Base and replaces Name.
type Derived struct{ Base }

func (Derived) Name() string { return "derived" }
