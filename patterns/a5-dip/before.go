// FileService reads user names from <dir>/<id>.txt.
type FileService struct{ dir string }

// NewFileService returns a service that reads <dir>/<id>.txt.
func NewFileService(dir string) *FileService { return &FileService{dir: dir} }

// Greeting returns "Hello, <name>!" for the user stored under id.
func (s *FileService) Greeting(id string) (string, error) {
	b, err := os.ReadFile(filepath.Join(s.dir, id+".txt"))
	if err != nil {
		return "", fmt.Errorf("greeting %q: %w", id, err)
	}
	return "Hello, " + strings.TrimSpace(string(b)) + "!", nil
}
